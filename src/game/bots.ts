export const BOTS_BY_ID = Object.fromEntries(BOT_ROSTER.map((b) => [b.id, b]));

export function getBotPersonality(id?: string): BotPersonality {
  if (id && BOTS_BY_ID[id]) return BOTS_BY_ID[id];
  return BOT_ROSTER[0];
}

export function getRandomBot(skill?: BotSkill): BotPersonality {
  const pool = skill ? BOT_ROSTER.filter((b) => b.skill === skill) : BOT_ROSTER;
  if (!pool.length) return BOT_ROSTER[0];
  return pool[Math.floor(Math.random() * pool.length)];
}
